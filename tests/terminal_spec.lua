local helpers = require('helpers')
local kiro = require('kiro')
local terminal = require('kiro.terminal')

describe('terminal lifecycle', function()
  after_each(helpers.cleanup)

  it('open creates the KiroChat buffer with a running job', function()
    assert.is_true(kiro.open())
    local info = terminal.info()
    assert.is_true(info.exists)
    assert.is_true(info.running)
    assert.is_true(info.job > 0)
    assert.are.equal('KiroChat', vim.fn.bufname(info.buffer))
    assert.are.equal(65, vim.api.nvim_win_get_width(0))
  end)

  it('honours chat_width from setup()', function()
    kiro.setup({ chat_width = 50 })
    kiro.open()
    assert.are.equal(50, vim.api.nvim_win_get_width(0))
  end)

  it('runs kiro-cli with --resume and the configured agent', function()
    local args_file = vim.fn.tempname()
    vim.env.KIRO_STUB_ARGS = args_file
    kiro.setup({ agent = 'my-agent' })
    kiro.open()
    vim.wait(2000, function()
      return vim.fn.filereadable(args_file) == 1
    end)
    vim.env.KIRO_STUB_ARGS = nil
    assert.are.same({ 'chat', '--resume', '--agent', 'my-agent' }, vim.fn.readfile(args_file))
  end)

  it('close hides the window but the job keeps running', function()
    kiro.open()
    local job = terminal.info().job
    kiro.close()
    assert.are.equal(1, vim.fn.winnr('$'))
    assert.are.equal(-1, vim.fn.bufwinid(terminal.info().buffer))
    assert.is_true(terminal.info().running)
    assert.are.equal(job, terminal.info().job)
  end)

  it('toggle twice shows the window again', function()
    kiro.open()
    kiro.toggle()
    assert.are.equal(-1, vim.fn.bufwinid(terminal.info().buffer))
    kiro.toggle()
    assert.are_not.equal(-1, vim.fn.bufwinid(terminal.info().buffer))
    assert.is_true(terminal.info().running)
  end)

  it('stop deletes the buffer and clears state', function()
    kiro.open()
    local buf = terminal.info().buffer
    kiro.stop()
    local info = terminal.info()
    assert.is_false(info.exists)
    assert.are.equal(-1, info.buffer)
    assert.are.equal(-1, info.job)
    assert.are.equal(0, vim.fn.buflisted(buf))
  end)

  it('open after the job exited replaces the dead buffer', function()
    kiro.open()
    local old = terminal.info()
    vim.fn.jobstop(old.job)
    vim.wait(2000, function()
      return vim.fn.jobwait({ old.job }, 0)[1] ~= -1
    end)
    vim.cmd('stopinsert')
    assert.is_true(kiro.open())
    local new = terminal.info()
    assert.is_true(new.running)
    assert.are_not.equal(old.buffer, new.buffer)
    assert.are_not.equal(old.job, new.job)
  end)

  it('open while visible keeps a single window and buffer', function()
    kiro.open()
    local buf = terminal.info().buffer
    kiro.open()
    assert.are.equal(buf, terminal.info().buffer)
    assert.are.equal(2, vim.fn.winnr('$'))
  end)

  it('close warns when Kiro is the only window', function()
    kiro.open()
    vim.cmd('only')
    local messages, restore = helpers.capture_echo()
    kiro.close()
    restore()
    assert.are.equal('Cannot hide Kiro because it is the only window', messages[1].text)
    assert.are.equal('WarningMsg', messages[1].hl)
  end)

  it('reports when there is nothing to close or stop', function()
    local messages, restore = helpers.capture_echo()
    kiro.close()
    kiro.stop()
    restore()
    assert.are.equal('Kiro chat is not running', messages[1].text)
    assert.are.equal('Kiro chat is not running', messages[2].text)
  end)

  it('reports an error when kiro-cli cannot be started', function()
    local path = vim.env.PATH
    vim.env.PATH = '/nonexistent'
    local messages, restore = helpers.capture_echo()
    local ok = kiro.open()
    restore()
    vim.env.PATH = path
    assert.is_false(ok)
    assert.are.equal('Unable to start Kiro CLI', messages[#messages].text)
    assert.are.equal(1, vim.fn.winnr('$'))
    assert.is_false(terminal.info().exists)
  end)
end)
